/*
===========================================================================
HZM coop [bug-3462] MODERN SCOPE VIEW - user 2026-10-05: "make all scopes look better, more modern/realistic".

Replaces the retail quarter-texture overlay (textures/hud/zoomoverlay, kartop/karbottom - one crosshair for every gun)
for every scoped rifle with a per-optic view:
  - the RETICLE of that optic (German Absehen 1, ZF4, M73B1, M84, PU, No.32, Type 97, Italian), drawn as a 2D quad
    sized to the lens; textures generated by docs/tools/gen_scope_reticles.py (no painted text or figures);
  - the optic's REAL MAGNIFICATION (cg_scopeTrueMag): the world fov is set to 2*atan(tan(40)/mag), magnification
    measured against MOHAA's 80-degree view. Client-side only: the server keeps its tik zoom fov, so STAT_INZOOM
    (<= 30), STAT_CROSSHAIR, the compass gate and the zoom spread are untouched, and the mouse slowdown follows the
    view because CG_SensitivityScale reads the final refdef fov;
  - a SMOOTH scope-in/out: the fov eases from the hip fov (log-tan space, so the zoom rate looks constant) while the
    housing closes in from outside the screen and the eye settles into the exit pupil from below;
  - the SCOPE SHADOW: the exit pupil trails the view's angular velocity (critically damped spring), wanders with
    breathing (calmer while the breath is held - the existing hold, unchanged) and bobs with movement;
  - the optics themselves (soft aperture, shadow, glass tint, rim vignette, a touch of chromatic fringe, the housing
    blurred and darkened instead of black) are the gl2 pass RB_HZMScope (renderergl2/tr_hzm_scope.c,
    glsl/hzmscope_fp.glsl), fed through r_ppScopeState. When that pass cannot run (gl1, r_postProcess 0) this file
    draws the aperture and the shadow itself from two 2D masks - no blur or fringe, but the same shape and motion.

Binoculars, the Spy Camera and the Bombing Run keep their retail overlays (CG_DrawZoomOverlay). cg_hzmScope 0 = the
retail scope exactly as before (overlay, server fov, no pass).
===========================================================================
*/
