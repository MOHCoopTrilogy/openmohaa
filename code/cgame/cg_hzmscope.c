static qhandle_t s_hRet[HO_NUM];
static qhandle_t s_hAperture, s_hEyebox;
static int       s_assets = -1; // -1 not probed yet, 0 the scopes pak is missing, 1 present

/*
CG_HzmScopeOn - the master switch AND the assets. zzzzzzzzzz_coop_scopes.pk3 is probed once per cgame load (a
vid_restart or a map change reloads cgame, so these handles cannot go stale). Without the pak the modern view is off
AS A WHOLE - retail overlay, server fov, no gl2 pass: before this the lens pass and the true magnification still ran
under the retail overlay on an install that had the engine but not the pak.
*/
static qboolean CG_HzmScopeOn(void)
{
    if (!cg_hzmScope->integer) {
        return qfalse;
    }
    if (s_assets < 0) {
        s_hAperture = cgi.R_RegisterShaderNoMip("textures/hud/coop_scope/aperture");
        s_hEyebox   = cgi.R_RegisterShaderNoMip("textures/hud/coop_scope/eyebox");
        s_assets    = (s_hAperture && s_hEyebox) ? 1 : 0;
    }
    return s_assets > 0 ? qtrue : qfalse;
}

// an optic's reticle: loaded when its rifle is first in the hands, not on the frame the scope comes up
static qhandle_t CG_HzmScopeReticle(int o)
{
    if (o < 0 || o >= HO_NUM) {
        return 0;
    }
    if (!s_hRet[o]) {
        s_hRet[o] = cgi.R_RegisterShaderNoMip(va("textures/hud/coop_scope/ret_%s", s_hzmOptics[o].tex));
    }
    return s_hRet[o];
}

/*
CG_HzmScopeWeaponOptic - optic index of a weapon name, -1 if it is not a known scope. Also used by cg_view.c's
CG_ActiveWeaponHasScope, whose own list predates the imported snipers (bug-256 coverage).
*/
int CG_HzmScopeWeaponOptic(const char *wpn)
{
    char   vb[64];
    size_t i;

    if (!wpn || !wpn[0]) {
        return -1;
    }
    if (CoopStripSkinSuffix(wpn, vb, sizeof(vb))) {
        wpn = vb;
    }
    for (i = 0; i < sizeof(s_hzmScopeWeaps) / sizeof(s_hzmScopeWeaps[0]); i++) {
        if (!Q_stricmp(wpn, s_hzmScopeWeaps[i].weapon)) {
            return s_hzmScopeWeaps[i].optic;
        }
    }
    return -1;
}

static const char *CG_HzmActiveWeaponName(void)
{
    if (!cg.snap || cg.snap->ps.activeItems[1] < 0) {
        return "";
    }
    return CG_ConfigString(CS_WEAPONS + cg.snap->ps.activeItems[1]);
}

// a zoom the modern view should own: a rifle scope (the server's <= 30 test), not a turret / vehicle sight
static qboolean CG_HzmScopeZoomed(int *optic, qboolean *known)
{
    const char *wpn;
    int         o;

    *optic = -1;
    *known = qfalse;
    if (!cg.snap || !cg_hzmScope->integer) {
        return qfalse;
    }
    wpn = CG_HzmActiveWeaponName();
    o   = CG_HzmScopeWeaponOptic(wpn);
    if (o >= 0 && CG_HzmScopeOn()) {
        CG_HzmScopeReticle(o); // the rifle is in the hands: have its reticle ready before the scope comes up
    }
    if (cg.snap->ps.stats[STAT_INZOOM] <= 0 || cg.snap->ps.stats[STAT_INZOOM] > 30) {
        return qfalse;
    }
    if (!CG_HzmScopeOn()) {
        return qfalse;
    }
    if (cg.snap->ps.pm_flags & (PMF_TURRET | PMF_CAMERA_VIEW)) {
        return qfalse;
    }
    if (strstr(wpn, "inocular") || !Q_stricmpn(wpn, "Spy Camera", 10) || !Q_stricmpn(wpn, "Bombing Run", 11)) {
        return qfalse; // these keep their retail overlays
    }
    if (o >= 0) {
        *optic = o;
        *known = qtrue;
    } else {
        *optic = HO_M73B1; // an unlisted scope: a plain crosshair, the tik's own fov
    }
    return qtrue;
}

static float CG_HzmSmooth(float t)
{
    if (t <= 0.0f) {
        return 0.0f;
    }
    if (t >= 1.0f) {
        return 1.0f;
    }
    return t * t * (3.0f - 2.0f * t);
}

static float CG_HzmAngleDelta(float a, float b)
{
    float d = a - b;
    while (d > 180.0f) {
        d -= 360.0f;
    }
    while (d < -180.0f) {
        d += 360.0f;
    }
    return d;
}

/*
CG_HzmScopeFrame - once per frame from CG_CalcFov: the ease, the shadow spring, and the publish to the gl2 pass.
*/
static void CG_HzmScopeFrame(float camFov)
{
    int      optic;
    qboolean known, zoomed;
    float    dt, k, tx, ty, yawVel, pitchVel, t, m;

    zoomed = CG_HzmScopeZoomed(&optic, &known);
    dt     = (cg.time - hs.lastTime) * 0.001f;
    if (dt < 0.0f || dt > 0.1f) {
        dt = 0.0f;
    }
    hs.lastTime = cg.time;

    // the un-zoomed fov the ease starts from and returns to. Only while fully out of the scope and only a real hip fov:
    // the server fov is lerped toward the zoom fov between snapshots BEFORE STAT_INZOOM reaches the predicted state, so
    // the frames just ahead of a scope-in carry 20-something degrees (s1: hip=24.8 - the ease had nothing to ease).
    hs.holdHip = qfalse;
    if (hs.frac <= 0.0f) {
        if (cg.nextSnap && cg.nextSnap->ps.stats[STAT_INZOOM] > 0 && cg.nextSnap->ps.stats[STAT_INZOOM] <= 30
            && CG_HzmScopeWeaponOptic(CG_HzmActiveWeaponName()) >= 0 && CG_HzmScopeOn()
            && cg_scopeTrueMag->integer) {
            hs.holdHip = qtrue; // the zoom is in the next snapshot: hold the hip view until the ease takes it
        } else if (camFov > 45.0f && (!cg.snap || !cg.snap->ps.stats[STAT_INZOOM])
                   && !cg.predicted_player_state.stats[STAT_INZOOM]) {
            hs.hipFov = camFov;
        }
    }

    if (zoomed) {
        if (hs.frac <= 0.0f || hs.optic != optic) {
            // a fresh scope-in: the eye comes up from below the eyepiece
            hs.sx = 0.0f;
            hs.sy = 0.42f;
            hs.vx = hs.vy = 0.0f;
        }
        hs.optic = optic;
        hs.remap = (known && cg_scopeTrueMag->integer) ? qtrue : qfalse;
        // [scopes1025] picture-in-picture only for a known optic on a renderer whose composite is live; decided at the scope-in and kept
        // through the ease-out so the view never changes mode mid-scope
        if (hs.frac <= 0.0f) {
            hs.pip = (hs.remap && cg_scopePip->integer && r_ppScopePipLive->integer && CG_HZM_RendererIsGl2()) ? qtrue : qfalse;
        }
        if (hs.remap) {
            hs.scopeFov = 2.0f * RAD2DEG(atan(tan(DEG2RAD(40.0f)) / s_hzmOptics[optic].mag));
        } else {
            hs.scopeFov = camFov;
        }
        k = (cg_scopeInTime->value > 0.01f) ? dt / cg_scopeInTime->value : 1.0f;
        hs.frac += k;
    } else {
        k = (cg_scopeOutTime->value > 0.01f) ? dt / cg_scopeOutTime->value : 1.0f;
        hs.frac -= k;
        if (!cg_hzmScope->integer) {
            hs.frac = 0.0f;
        }
    }
    if (hs.frac > 1.0f) {
        hs.frac = 1.0f;
    }
    if (hs.frac < 0.0f) {
        hs.frac = 0.0f;
    }
    hs.ease = CG_HzmSmooth(hs.frac);
    if (hs.frac <= 0.0f) {
        hs.pip = qfalse;
    }
    hs.lensFov = 0.0f;
    hs.lensK   = 1.0f;
    if (hs.pip) {
        // the aim pose's share of what is on screen (cg_view.c CG_AdsAnimGate: 1 aimed / fire / bolt, falls to 0 for a reload or a
        // switch): the lens fades out with it, so the hands and the parts read in the wide view and come back to the eye with the pose
        float g = CG_AdsAnimGate();
        hs.lensK = CG_HzmSmooth((g - 0.15f) / 0.6f);
        // the lens only shows once the rifle has ARRIVED at the eye (ADS pose 0.65 .. 0.95): the rifle body carries the raise, and the
        // short fade then goes from the dark ocular straight into the lens - no long ghosted double image of two views. Out is the reverse.
        hs.lensK *= CG_HzmSmooth((CG_AdsPoseFactor() - 0.65f) / 0.30f);
    }
    if (hs.pip && hs.optic >= 0) {
        // the lens square: the lens circle (cg_scopeRadius of the screen height) plus a 4 percent margin, at the optic's magnification
        // (vertical half-tan of the old full-screen scope view = 0.75 * tan(scopeFov / 2), 4:3 reference)
        float scopeHalfTan = (float)tan(DEG2RAD(hs.scopeFov * 0.5f));
        float halfTan      = 1.04f * 2.0f * cg_scopeRadius->value * 0.75f * scopeHalfTan;
        hs.lensFov         = 2.0f * RAD2DEG((float)atan(halfTan));
    }

    // ---- scope shadow: where the eye sits behind the eyepiece
    yawVel = pitchVel = 0.0f;
    if (hs.haveAng && dt > 0.0f) {
        yawVel   = CG_HzmAngleDelta(cg.refdefViewAngles[YAW], hs.lastYaw) / dt;
        pitchVel = CG_HzmAngleDelta(cg.refdefViewAngles[PITCH], hs.lastPitch) / dt;
    }
    hs.lastYaw   = cg.refdefViewAngles[YAW];
    hs.lastPitch = cg.refdefViewAngles[PITCH];
    hs.haveAng   = qtrue;

    if (hs.frac > 0.0f && dt > 0.0f) {
        float  sh = cg_scopeShadow->value;
        float  sp, bob, len;
        vec3_t v;

        // the head lags the rifle: the clear pupil trails the swing (turning right = yaw falling = pupil left)
        tx = 0.0035f * yawVel;
        ty = -0.0035f * pitchVel;
        // breathing wander, calmer while the breath is held (CG_IsBreathSteady = the existing hold)
        t  = cg.time * 0.001f;
        m  = CG_IsBreathSteady() ? 0.25f : 1.0f;
        tx += m * 0.012f * (float)sin(t * 1.15f);
        ty += m * 0.018f * (float)sin(t * 0.73f + 1.3f);
        // moving with the scope up bobs the eye on the cheek weld
        VectorCopy(cg.predicted_player_state.velocity, v);
        v[2] = 0.0f;
        sp  = VectorLength(v);
        bob = 0.07f * (sp > 160.0f ? 1.0f : sp / 160.0f);
        tx += bob * (float)sin(t * 2.0f * M_PI * 0.95f);
        ty += bob * 0.7f * (float)fabs(cos(t * 2.0f * M_PI * 0.95f));
        tx *= sh;
        ty *= sh;
        len = (float)sqrt(tx * tx + ty * ty);
        if (len > 0.34f) {
            tx *= 0.34f / len;
            ty *= 0.34f / len;
        }
        // critically damped spring (omega 13/s): no overshoot, a soft follow
        {
            const float w = 13.0f;
            float       ax = w * w * (tx - hs.sx) - 2.0f * w * hs.vx;
            float       ay = w * w * (ty - hs.sy) - 2.0f * w * hs.vy;
            hs.vx += ax * dt;
            hs.vy += ay * dt;
            hs.sx += hs.vx * dt;
            hs.sy += hs.vy * dt;
        }
    }

    // ---- publish to the gl2 pass (only on change; "0" once when the scope is down)
    hs.lens = cg_scopeRadius->value * (hs.pip ? 1.0f : (1.0f + 0.55f * (1.0f - hs.ease)));
    hs.eye  = 1.18f; // with the pupil's 0.86..1.0 fall-off: a centred eye casts no shadow at all
    {
        char buf[128];
        if (hs.frac <= 0.0f) {
            Q_strncpyz(buf, "0", sizeof(buf));
        } else {
            Com_sprintf(
                buf,
                sizeof(buf),
                "%.4f %.4f %.4f %.4f %.3f %.3f %.3f",
                hs.ease * hs.lensK,
                hs.lens,
                hs.sx,
                hs.sy,
                hs.eye,
                s_hzmOptics[hs.optic >= 0 ? hs.optic : HO_M73B1].warm,
                hs.lensFov
            );
        }
        if (strcmp(buf, hs.pub)) {
            Q_strncpyz(hs.pub, buf, sizeof(hs.pub));
            cgi.Cvar_Set("r_ppScopeState", buf);
        }
    }

    if (cg_scopeDebug->integer && hs.frac > 0.0f && (cg_scopeDebug->integer > 1 || cg.time - hs.dbgTime > 1000)) {
        hs.dbgTime = cg.time;
        cgi.Printf(
            "^~^~^ SCOPE optic=%s remap=%d frac=%.2f fov=%.1f hip=%.1f pupil=%.3f,%.3f live=%d\n",
            s_hzmOptics[hs.optic >= 0 ? hs.optic : HO_M73B1].tex,
            hs.remap,
            hs.frac,
            hs.scopeFov,
            hs.hipFov,
            hs.sx,
            hs.sy,
            r_ppScopeLive->integer
        );
    }
}

/*
CG_HzmScopeWorldFov - the pre-aspect world fov while the modern scope owns it (scoped, or easing out).
Returns qfalse when it does not, and the caller keeps its own fov. Runs the per-frame update.
*/
qboolean CG_HzmScopeWorldFov(float camFov, float *outFov)
{
    float a, b, e;

    CG_HzmScopeCvars();
    CG_HzmScopeFrame(camFov);

    if (hs.holdHip && hs.frac <= 0.0f) {
        *outFov = hs.hipFov;
        return qtrue;
    }
    if (hs.pip && hs.frac > 0.0f && hs.hipFov > 1.0f) {
        *outFov = hs.hipFov; // [scopes1025] the MAIN view stays wide; the zoom is the lens scene (renderer)
        return qtrue;
    }
    if (hs.frac <= 0.0f || (hs.ease >= 0.9999f && !hs.remap)) {
        return qfalse; // unlisted scope fully in: the server's fov, untouched
    }
    if (hs.hipFov < 1.0f || hs.scopeFov < 1.0f) {
        return qfalse;
    }
    e = hs.ease;
    a = (float)log(tan(DEG2RAD(hs.hipFov * 0.5f)));
    b = (float)log(tan(DEG2RAD(hs.scopeFov * 0.5f)));
    *outFov = 2.0f * RAD2DEG(atan(exp(a + (b - a) * e)));
    return qtrue;
}

// [scopes1025] helpers for cg_view.c / cg_modelanim.c
qboolean CG_HzmScopePipActive(void)
{
    return (cg_hzmScope && hs.pip && hs.frac > 0.0f) ? qtrue : qfalse;
}

// the rifle stays drawn and is raised to the eye through the ADS pose while a PiP scope is up
qboolean CG_HzmScopeRaiseOwns(void)
{
    return (CG_HzmScopePipActive() && cg_scopeRaise && cg_scopeRaise->integer) ? qtrue : qfalse;
}

// mouse sensitivity scale of the lens against the wide view, eased with the scope (1 outside PiP)
float CG_HzmScopeSensScale(void)
{
    float a, b;

    if (!CG_HzmScopePipActive() || hs.hipFov < 1.0f || hs.scopeFov < 1.0f) {
        return 1.0f;
    }
    a = (float)tan(DEG2RAD(hs.scopeFov * 0.5f)) / (float)tan(DEG2RAD(hs.hipFov * 0.5f));
    b = (float)exp(log(a) * hs.ease);
    return b;
}

qboolean CG_HzmScopeActive(void)
{
    return (cg_hzmScope && hs.frac > 0.0f) ? qtrue : qfalse;
}

// the un-zoomed camera fov (pre-aspect) the ease starts from: cg_view.c draws the gun with it while this owns the view
float CG_HzmScopeHipFov(void)
{
    return hs.hipFov;
}

/*
CG_HzmScopeOwnsAds - the rifle in the hands is one the modern view owns: its ADS button IS the scope toggle, so
cg_view.c's CG_AimingDownSights answers "no" for it even while the button is down and the scope is not up.
[bug-3462 follow-up, 2026-10-12] It answered "yes", so a held press ran the iron-sight ADS view on top of the toggle:
the press that scoped OUT was followed, 0.2 s after it, by a one-frame 1.4x zoom with the rifle rising (run sc_ease,
frames 64-66) for as long as the button stayed down, and the press that scoped IN lifted the gun for the frames before
the server's zoom arrived. Off with cg_hzmScope 0 or without the scopes pak - then it is exactly as before.
*/
qboolean CG_HzmScopeOwnsAds(void)
{
    CG_HzmScopeCvars();
    if (!CG_HzmScopeOn()) {
        return qfalse;
    }
    return CG_HzmScopeWeaponOptic(CG_HzmActiveWeaponName()) >= 0 ? qtrue : qfalse;
}

// solid black from the mask texture's own opaque corner (s1d: a "*white" fill drew grey boxes with white rims on gl1)
static void CG_HzmFill(float x0, float y0, float x1, float y1, qhandle_t h)
{
    if (x1 > x0 && y1 > y0) {
        cgi.R_DrawStretchPic(x0, y0, x1 - x0, y1 - y0, 0.0f, 0.0f, 0.02f, 0.02f, h);
    }
}

// a black circular mask of radius rad at (cx, cy): its texture quad, and solid black everywhere else inside clip
static void CG_HzmMask(float cx, float cy, float rad, qhandle_t tex, const float *clip)
{
    float x0 = cx - rad, y0 = cy - rad, x1 = cx + rad, y1 = cy + rad;

    cgi.R_DrawStretchPic(x0, y0, x1 - x0, y1 - y0, 0.0f, 0.0f, 1.0f, 1.0f, tex);
    CG_HzmFill(clip[0], clip[1], clip[2], y0 < clip[3] ? (y0 > clip[1] ? y0 : clip[1]) : clip[3], tex);
    CG_HzmFill(clip[0], y1 > clip[1] ? y1 : clip[1], clip[2], clip[3], tex);
    {
        float ya = y0 > clip[1] ? y0 : clip[1];
        float yb = y1 < clip[3] ? y1 : clip[3];
        CG_HzmFill(clip[0], ya, x0 < clip[2] ? x0 : clip[2], yb, tex);
        CG_HzmFill(x1 > clip[0] ? x1 : clip[0], ya, clip[2], yb, tex);
    }
}

/*
CG_HzmScopeDraw2D - from CG_DrawZoomOverlay. Returns qtrue when the modern scope drew (the retail overlay must not).
*/
qboolean CG_HzmScopeDraw2D(void)
{
    qhandle_t hRet, hAperture, hEyebox;
    float     W, H, cx, cy, R;
    vec4_t    col;

    CG_HzmScopeCvars();
    if (hs.frac <= 0.0f || hs.optic < 0 || s_assets <= 0) {
        return qfalse; // not scoped, or the scopes pak is missing (then hs.frac never left 0): the retail overlay draws
    }
    hRet      = CG_HzmScopeReticle(hs.optic);
    hAperture = s_hAperture;
    hEyebox   = s_hEyebox;

    W  = (float)cgs.glconfig.vidWidth;
    H  = (float)cgs.glconfig.vidHeight;
    cx = W * 0.5f;
    cy = H * 0.5f;
    R  = hs.lens * H;

    // gl1 / no post chain: the aperture and the scope shadow from two 2D masks (the gl2 pass does both, with the
    // blur and the glass, when it runs - never both at once)
    if (!(r_ppScopeLive->integer && CG_HZM_RendererIsGl2()) && hAperture && hEyebox) {
        float clip[4];

        clip[0] = 0.0f;
        clip[1] = 0.0f;
        clip[2] = W;
        clip[3] = H;
        // OPAQUE black housing. It was 0.93: with no blur the 7% that showed through was the sharp magnified scene
        // carrying on past the lens rim out to the pupil mask - a second, ghost rim (run sc_variants v__22, gl1 too)
        VectorSet4(col, 0.0f, 0.0f, 0.0f, hs.ease);
        cgi.R_SetColor(col);
        CG_HzmMask(cx, cy, R, hAperture, clip);
        // the shadow mask fills the whole screen too: clipping its fill to the lens box left the housing darkened twice
        // inside the pupil's square only, a hard vertical edge either side of the lens (review 1, gl1)
        VectorSet4(col, 0.0f, 0.0f, 0.0f, hs.ease);
        cgi.R_SetColor(col);
        CG_HzmMask(cx + hs.sx * R, cy + hs.sy * R, hs.eye * R, hEyebox, clip);
    }

    // the reticle: in the scope, so it scales with the lens; centred - it marks the bore, the shadow does not move it.
    // Drawn black through rgbGen global (white read as a faint purple, 13/6/13, against bright walls - s2)
    // It fades in late (ease^3): mid-ease the lens is still wider than the screen and only half dark, and a full-strength
    // reticle there read as lines drawn outside the scope (review 1).
    VectorSet4(col, 0.0f, 0.0f, 0.0f, hs.ease * hs.ease * hs.ease * hs.lensK);
    cgi.R_SetColor(col);
    if (hRet) {
        cgi.R_DrawStretchPic(cx - R, cy - R, 2.0f * R, 2.0f * R, 0.0f, 0.0f, 1.0f, 1.0f, hRet);
    }
    cgi.R_SetColor(NULL);
    return qtrue;
}
